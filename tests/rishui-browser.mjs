// « ממבחני רישוי » sur un S24 : lien depuis l'accueil du quiz, choix de l'époque, manche de 10, solution non officielle + lien PDF,
// ordre des réponses conservé, résultat, bouton retour vers les examens, pas de défilement horizontal.
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { chromium } from 'playwright-core';
const ROOT = new URL('../public/', import.meta.url).pathname, OUT = process.argv[2];
const T = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.webp': 'image/webp' };
const srv = createServer(async (q, r) => { const p = normalize(decodeURIComponent(new URL(q.url, 'http://x').pathname)).replace(/^\/+/, '') || 'index.html'; try { const b = await readFile(join(ROOT, p)); r.writeHead(200, { 'content-type': T[extname(p)] || 'application/octet-stream' }); r.end(b); } catch { r.writeHead(404); r.end(); } });
await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}/`;
const br = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--no-sandbox'] });
const ctx = await br.newContext({ viewport: { width: 360, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'he-IL', serviceWorkers: 'block' });
await ctx.route(/supabase|tile/, r => r.abort());
const errs = []; let bad = 0; const check = (c, m) => { console.log((c ? '✅ ' : '❌ ') + m); if (!c) bad++; };
const pg = await ctx.newPage(); pg.on('pageerror', e => errs.push(e.message));
await pg.goto(base + 'parta.html'); await pg.waitForSelector('.rishui-link');
check(await pg.isVisible('.rishui-link'), 'accueil du quiz : lien « ממבחני רישוי »');
await pg.click('.rishui-link'); await pg.waitForSelector('#rstart');
check((await pg.textContent('h1')).includes('ממבחני רישוי'), 'page des examens');
check(/פתרון לא רשמי/.test(await pg.textContent('.hero')), 'avertissement : solution non officielle');
if (OUT) await pg.screenshot({ path: OUT + '/rishui-home.png', fullPage: true });
await pg.click('[data-era="new"]'); await pg.waitForTimeout(200);
check((await pg.getAttribute('[data-era="new"]', 'aria-pressed')) === 'true', 'filtre 2018–2024');
await pg.click('#rstart'); await pg.waitForSelector('.ans');
const D = await pg.evaluate(() => window.MDPartAApp.rishui());
const st = await pg.evaluate(() => window.MDPartAApp.state().run);
check(st.src === 'rishui' && st.items.length > 0 && st.items.length <= 10, 'manche de ' + st.items.length + ' questions');
const it = st.items[0], orig = D.questions.find(q => q.id === it.id);
check(JSON.stringify(orig.options) === JSON.stringify(it.options), 'ordre des réponses identique au PDF');
check(st.items.every(x => x.rishui.kind === 'exam'), 'seulement des examens 2018–2024');
await pg.click(`.ans[data-k="${it.correct}"]`); await pg.waitForSelector('.rishui-src');
check(/שאלה \d+/.test(await pg.textContent('.rishui-src')) && await pg.isVisible('.rishui-src a'), 'source : numéro, examen, lien PDF');
if (OUT) await pg.screenshot({ path: OUT + '/rishui-answer.png', fullPage: true });
await pg.click('#quit'); await pg.waitForSelector('.res');
check((await pg.getAttribute('.go a.btn', 'href')) === '#/rishui', 'résultat : retour aux examens');
const pts = await pg.evaluate(() => window.MDProgress && window.MDProgress.partAStats().known.filter(id => id.startsWith('Q-rishui_')).length);
check(pts >= 1, 'progression enregistrée');
const over = await pg.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
check(over <= 0, 'pas de défilement horizontal');
check(!errs.length, 'aucune erreur JS ' + errs.join(' | '));
await br.close(); srv.close(); process.exit(bad ? 1 : 0);
